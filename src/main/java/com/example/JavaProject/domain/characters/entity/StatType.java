package com.example.JavaProject.domain.characters.entity;

public enum StatType {
    VITALITY,       // 체력: 신체적 건강과 활동 능력
    CHARISMA,       // 매력: 타인을 끌어들이고 설득하는 능력
    WISDOM,         // 지혜: 판단력과 문제 해결 능력
    STEALTH,        // 은밀: 비밀 행동 및 정보 은폐 능력
    COMBAT,         // 전투: 물리적 위협에 대응하는 능력
    SOCIAL,         // 사교: 인간관계 형성 및 협상 능력
    SURVIVAL,       // 생존: 위기 상황에서 살아남는 능력
    MAGIC,          // 마력: 초자연적인 힘을 다루는 능력

    POLITICS,       // 정치력: 권력 관계 파악 및 정치적 협상 능력
    LEADERSHIP,     // 통솔력: 조직과 인력을 이끄는 능력
    ADMINISTRATION, // 행정력: 예산, 인력, 시설을 효율적으로 관리하는 능력
    INTELLIGENCE    // 정보력: 조직 내부의 정보와 비밀을 수집·분석하는 능력
}